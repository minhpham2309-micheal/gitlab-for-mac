use gpui_kit::{App, KeyBinding};

gpui_kit::actions!(
    glab,
    [
        TogglePalette,
        OpenFindFile,
        NavBack,
        NavForward,
        GoProjects,
        GoOverview,
        GoRepository,
        GoPipelines,
        GoMergeRequests,
        GoBranches,
        GoTags,
        GoCommits,
        GoIssues,
        GoTodos,
        GoReleases,
        GoSchedules,
        GoRunners,
        GoSearch,
        GoConsole,
        GoPreferences,
        ZoomIn,
        ZoomOut,
        ZoomReset,
        RefreshScreen,
        ToggleFollowLog,
        FocusLogSearch,
        LogFindNext,
        LogFindPrev,
        CopyFullLog,
        ToggleSidebar,
        ToggleTheme,
        OpenInBrowser,
        DismissOverlay,
        RunPipelineAction,
        RetryPipelineAction,
        CancelPipelineAction,
        RetryJobAction,
        CancelJobAction,
        PlayJobAction,
        DownloadArtifactsAction,
        ApproveMrAction,
        MergeMrAction,
        CloseMrAction,
    ]
);

pub fn bind_keys(cx: &mut App) {
    cx.bind_keys([
        KeyBinding::new("cmd-k", TogglePalette, None),
        KeyBinding::new("cmd-t", OpenFindFile, None),
        KeyBinding::new("cmd-[", NavBack, None),
        KeyBinding::new("cmd-]", NavForward, None),
        KeyBinding::new("cmd-p", GoProjects, None),
        KeyBinding::new("cmd-r", RefreshScreen, None),
        KeyBinding::new("cmd-l", ToggleFollowLog, None),
        KeyBinding::new("cmd-f", FocusLogSearch, None),
        KeyBinding::new("cmd-g", LogFindNext, None),
        KeyBinding::new("cmd-shift-g", LogFindPrev, None),
        KeyBinding::new("cmd-shift-c", CopyFullLog, None),
        KeyBinding::new("cmd-\\", ToggleSidebar, None),
        KeyBinding::new("cmd-shift-t", ToggleTheme, None),
        KeyBinding::new("cmd-,", GoPreferences, None),
        KeyBinding::new("cmd-=", ZoomIn, None),
        KeyBinding::new("cmd--", ZoomOut, None),
        KeyBinding::new("cmd-0", ZoomReset, None),
        KeyBinding::new("escape", DismissOverlay, None),
    ]);
}
